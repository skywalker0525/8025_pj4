def update_nested(data: dict, keys, value) -> None:
    cur = data
    for key in keys[:-1]:
        cur = cur[key]
    cur[keys[-1]] = value


def write_nav2_params(path: Path) -> None:
    source_path = NAV_DIR / "config" / "nav2_params_small_house.yaml"
    with source_path.open("r", encoding="utf-8") as handle:
        data = yaml.safe_load(handle)
    update_nested(data, ["amcl", "ros__parameters", "initial_pose", "x"], START[0])
    update_nested(data, ["amcl", "ros__parameters", "initial_pose", "y"], START[1])
    update_nested(data, ["amcl", "ros__parameters", "initial_pose", "yaw"], START[2])
    update_nested(
        data,
        ["controller_server", "ros__parameters", "progress_checker", "movement_time_allowance"],
        75.0,
    )
    update_nested(
        data,
        ["planner_server", "ros__parameters", "GridBased", "tolerance"],
        0.75,
    )
    update_nested(
        data,
        ["global_costmap", "global_costmap", "ros__parameters", "inflation_layer", "inflation_radius"],
        0.35,
    )
    update_nested(
        data,
        ["local_costmap", "local_costmap", "ros__parameters", "inflation_layer", "inflation_radius"],
        0.35,
    )
    path.write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")


def main() -> int:
    obstacles = all_obstacles(include_boundary=True)
    write_world(WORLD_PATH, obstacles)
    write_pgm(MAP_PGM_PATH, obstacles)
    write_map_yaml(MAP_YAML_PATH)
    write_waypoints(WAYPOINTS_PATH)
    write_nav2_params(NAV2_PARAMS_PATH)
    for path in [WORLD_PATH, MAP_PGM_PATH, MAP_YAML_PATH, WAYPOINTS_PATH, NAV2_PARAMS_PATH]:
        print(path.relative_to(REPO_ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
